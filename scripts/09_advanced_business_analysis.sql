--3.Revenue by customer segment
/*
OBJECTIVE:It divides the customers into 3 segments based on their revenue
*/
SELECT
CASE
WHEN MonthlyCharges>=80 THEN 'High Value'
WHEN MonthlyCharges BETWEEN 50 AND 79.99 THEN 'Medium Value'
ELSE 'Low Value'
END AS CustomerSegment,
COUNT(*) AS Customers,
ROUND(SUM(MonthlyCharges),2) AS MonthlyRevenue
FROM customer_churn
GROUP BY 
CASE
WHEN MonthlyCharges>=80 THEN 'High Value'
WHEN MonthlyCharges BETWEEN 50 AND 79.99 THEN 'Medium Value'
ELSE 'Low Value'
END
ORDER BY MonthlyRevenue DESC;

/*
INSIGHTS:Shows which customer segment contributes the highest monthly revenue.
RECOMMENDATION:Invest more in retaining High Value customers.
*/
--------------------------------------------------------------------------------------------
--4.Prercentile analysis
/*
OBJECTIVE:It divides and identifies the customers as different groups based on their expenses
*/
SELECT
customerID,
MonthlyCharges,
NTILE(4) OVER(
ORDER BY MonthlyCharges DESC
) AS RevenueQuartile
FROM customer_churn;

/*
INSIGHTS:Divides customers into four spending groups.
RECOMMENDATION:Target premium offers to the top 25% spending customers.
*/
--------------------------------------------------------------------------------------------
