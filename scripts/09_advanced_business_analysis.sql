--1.Customer lifetime value
--------------------------------------------------------------------------------------------
/*
OBJECTIVE:To identify the lifetime value of the customer
*/ 
SELECT top 10
    customerID,
    tenure,
    MonthlyCharges,
    ROUND(tenure * MonthlyCharges,2) AS Customer_Lifetime_Value
FROM customer_churn
ORDER BY Customer_Lifetime_Value DESC;

/*
INSIGHTS:Customers with long tenure and high monthly plans generate the highest revenue.
         Losing these customers would have a significant financial impact.
RECOMMENDATION:Create VIP retention programs.
               Offer loyalty discounts after 2–3 years.
               Assign dedicated customer support for high-value customers.
*/
---------------------------------------------------------------------------------------------------------
--2.Rank customers by revenue
/*OBJECTIVE:It ranks the based on their revenue
*/
select
customerid,
monthlycharges,
tenure,
round(monthlycharges*tenure,2) as revenue,
rank() over(order by monthlycharges desc) as revenue_rank
from Customer_Churn

/*
INSIGHTS:Ranks customers from highest to lowest revenue.
RECOMMENDATION:Top-ranked customers should receive
               Premium support
               Exclusive offers
               Loyalty rewards
*/
