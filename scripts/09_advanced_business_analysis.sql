--6.Churn prediction
/*OBJECTIVE:It divides the customers into different categories giving them risk scores inorder to predict the churn
            and to prevent high churn rate.
*/
SELECT
customerID,
CASE
WHEN Contract='Month-to-month' THEN 3 
WHEN TechSupport='0' THEN 2 
WHEN OnlineSecurity='0' THEN 2 
WHEN tenure<12 THEN 3 ELSE 0 END
AS RiskScore
FROM customer_churn
ORDER BY RiskScore DESC;

/*
INSIGHTS:Creates a simple churn risk score based on multiple factors.
RECOMMENDATION:Customers with higher scores should receive 
               proactive retention calls, service upgrades, or personalized offers.
*/
--------------------------------------------------------------------------------------------
--7.Which contract type has the highest churn rate
/*
OBJECTIVE:Analyze customer churn across different contract types to identify
          which contracts are most vulnerable to customer loss.
*/
WITH Contract_Churn AS
(
    SELECT
        Contract,
        COUNT(*) AS Total_Customers,
        SUM(CASE WHEN Churn = 1 THEN 1 ELSE 0 END) AS Churned_Customers
    FROM dbo.Customer_Churn
    GROUP BY Contract
)

SELECT
    Contract,
    Total_Customers,
    Churned_Customers,
    ROUND(Churned_Customers * 100.0 / Total_Customers, 2) AS Churn_Rate
FROM Contract_Churn
ORDER BY Churn_Rate DESC;

/* 
INSIGHTS:-Month-to-month customers have an extremely high churn rate (42.71%).
         -Customers on two-year contracts are the most loyal.
RECOMMENDATIONS:Offer discounts or incentives to encourage month-to-month customers 
                to switch to one-year or two-year contracts.
*/
