--11.View of high risk customeres
/*
OBJECTIVE:Creates a reusable view containing churned month-to-month customers.
*/
CREATE VIEW  High_Risk_Customers  AS

SELECT
    customerID,
    Contract,
    tenure,
    MonthlyCharges
FROM Customer_Churn
WHERE Churn=1
AND Contract='Month-to-month';
--to verify the view is created:
SELECT * from high_risk_customers

/*
INSIGHTS:This view enables analysts to quickly access the highest-risk customer
         segment without rewriting the query.
RECOMMENDATIONS:Use this view for recurring retention analysis and reporting.
